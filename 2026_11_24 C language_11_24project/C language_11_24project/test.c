/* ============================================================================
 * 题 6：求给定序列前 n 项和（1! + 2! + ... + n!）
 * 输入正整数 n，求 e = 1! + 2! + 3! + ... + n!。
 * 要求定义并调用函数 fact(n) 计算 n!，函数类型是 double。
 *
 * 备注 / 易错点：
 *   - fact() 是连乘，product 必须初始化为 1；如果写成 0，
 *     0 乘任何数都是 0，阶乘永远是 0（这个坑之前踩过，已改）。
 *   - fact 的返回类型是 double，n 很大时不会先溢出 int；
 *     但 n 超过 170 左右时 double 也会溢出成 inf。
 *   - main 里 e 从 0 开始，把 1! 到 n! 一项项累加。
 *   - 这是当前唯一生效的程序，其余题目都是注释块。
 * ============================================================================ */
double fact(int x);

int main()
{
	int i, n;
	double e = 0;
	printf("input n:");
	scanf("%d", &n);
	for (i = 1;i <= n;i++)
	{
		e += fact(i);
	}
	printf("结果为%lf\n", e);

	return 0;
}
double fact(int n)
{
	int i;
	double product = 1;
	for (i = 1;i <= n;i++)
	{
		product *= i;
	}
	return product;
}
