#pragma once

/*
 * ============================================================================
 *  扫雷游戏（控制台版）—— game.h
 * ============================================================================
 *
 *  【这个文件是做什么的？】
 *  它只负责“声明”：告诉编译器有哪些常量、结构体和函数。
 *  函数真正的代码在 game.c 里，程序入口 main 在 test.c 里。
 *
 *  【三个文件的关系】
 *      test.c  —— 主程序：显示菜单、读玩家输入、调用游戏功能
 *      game.c  —— 游戏核心：布雷、翻格子、插旗、判断胜负
 *      game.h  —— 上面两个文件共同遵守的“说明书”
 *
 *  【为什么开头写 #pragma once？】
 *  防止同一个头文件被重复包含，避免“重复定义”的编译错误。
 * ============================================================================
 */

/* ---------------------------------------------------------------------------
 * 棋盘的最大尺寸
 * 数组的大小必须在编译时确定，所以用宏（预处理时直接替换）定义常量。
 * 目前最大支持 30 行 × 30 列，足够下面三个难度使用。
 * ------------------------------------------------------------------------- */
#define MAX_ROWS 30
#define MAX_COLS 30

/* ---------------------------------------------------------------------------
 * 格子在屏幕上的显示字符
 * 把这些字符定义成宏，可以避免程序里到处写 '#'、'F' 这种“魔法字符”，
 * 以后想换显示样式，只改这里就行。
 * ------------------------------------------------------------------------- */
#define CELL_HIDDEN '#'   /* 还没翻开 */
#define CELL_FLAG   'F'   /* 玩家插的小旗 */
#define CELL_MINE   '*'   /* 地雷（游戏结束时显示） */
#define CELL_EMPTY  '.'   /* 已翻开，并且周围 8 格都没有雷 */
#define CELL_WRONG  'X'   /* 游戏结束时，发现旗插错了 */

/* ---------------------------------------------------------------------------
 * game_dig()（翻开格子）的返回值
 * ------------------------------------------------------------------------- */
#define DIG_OK       0    /* 正常翻开 */
#define DIG_EXPLODE  1    /* 踩到地雷 */
#define DIG_INVALID -1    /* 坐标非法、已翻开或已插旗，不能操作 */

/* ---------------------------------------------------------------------------
 * 游戏的三种状态
 * 用 enum（枚举）给整数起名字，代码比直接写 0、1、2 更好读。
 * ------------------------------------------------------------------------- */
typedef enum {
    STATE_PLAYING = 0,   /* 正在进行 */
    STATE_WON,           /* 胜利 */
    STATE_LOST           /* 失败 */
} GameState;

/* ---------------------------------------------------------------------------
 * 结构体 Game：把“一局游戏”的所有数据打包在一起
 *
 * 为什么这样设计？
 *   如果每个函数都单独传 rows、cols、mine……参数会非常多。
 *   打包成一个结构体后，函数只要收到一个 Game * 指针，
 *   就能访问这一局的所有数据，既清晰又方便以后同时开多局。
 *
 * 两个棋盘的分工：
 *   mine[][] 是“答案”，记录哪里有雷，只给程序看；
 *   show[][] 是“卷面”，记录玩家当前看到的内容，用来打印。
 * ------------------------------------------------------------------------- */
typedef struct {
    char mine[MAX_ROWS][MAX_COLS];  /* 雷区：'1' 表示有雷，'0' 表示没雷 */
    char show[MAX_ROWS][MAX_COLS];  /* 展示区：'#'、'F'、'.'、数字等 */
    int rows;                       /* 本局实际行数 */
    int cols;                       /* 本局实际列数 */
    int mine_count;                 /* 地雷总数 */
    int opened_count;               /* 已经翻开的格子数（用来判断胜利） */
    int flag_count;                 /* 已经插了多少面旗 */
    int first_dig;                  /* 1 = 还没翻过格子，用于“首击保护” */
    GameState state;                /* 当前游戏状态 */
} Game;

/* ---------------------------------------------------------------------------
 * 下面这些函数由 game.c 实现，供 test.c 调用。
 * 每个函数前面的注释说明了用途、参数和返回值。
 * ------------------------------------------------------------------------- */

/*
 * 初始化一局游戏。
 *   rows  —— 行数
 *   cols  —— 列数
 *   mines —— 地雷数量
 * 说明：初始化时并不会布雷，要等玩家第一次翻开格子时才布雷，
 *       这样才能保证“第一下永远不会踩雷”（首击保护）。
 */
void game_init(Game *game, int rows, int cols, int mines);

/*
 * 在屏幕上打印当前棋盘，以及剩余雷数、已翻开格子数。
 * 参数加了 const，表示这个函数只读数据，不会修改游戏。
 */
void game_print(const Game *game);

/*
 * 翻开第 row 行、第 col 列的格子。
 * 注意：行和列都从 0 开始数（玩家输入的是从 1 开始，test.c 会做转换）。
 * 返回值：DIG_OK / DIG_EXPLODE / DIG_INVALID，含义见上面的宏。
 */
int game_dig(Game *game, int row, int col);

/*
 * 插旗或取消旗（对同一格再操作一次就是取消）。
 * 返回值：
 *    1  —— 操作成功（插上旗，或取消了旗）
 *    0  —— 这个格子已经翻开，不能再插旗
 *   -1  —— 坐标非法，或者游戏已经结束
 */
int game_flag(Game *game, int row, int col);

/*
 * 游戏结束时调用：把所有地雷显示出来，并把插错的旗标成 'X'。
 * 这样玩家可以复盘，看看自己哪一步判断错了。
 */
void game_reveal_all(Game *game);
